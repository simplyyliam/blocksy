//! Blocksy's thin native layer (plan rule 2.2.8): files, processes, OS dialogs,
//! updates. All product logic lives in TypeScript.

mod commands;
mod error;
mod events;
mod process;

use commands::{bench, files, gradle, java, updater};
use tauri_specta::{collect_commands, collect_events, Builder};

/// Where the generated TypeScript bindings go. Never edit that file by hand.
const BINDINGS_PATH: &str = "../src/shared/bindings.ts";

/// Lists every command and event. This is what bindings.ts is generated from.
fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            files::default_projects_dir,
            files::write_project_files,
            files::read_text_file,
            files::write_text_file,
            files::path_exists,
            files::load_app_data,
            files::save_app_data,
            java::detect_java,
            gradle::run_gradle,
            gradle::stop_gradle,
            gradle::gradle_status,
            gradle::export_jar,
            updater::update_status,
            updater::check_for_updates,
            updater::install_update,
            bench::bench_mode,
            bench::app_uptime_ms,
            bench::bench_finish,
        ])
        .events(collect_events![
            events::GradleOutput,
            events::GradleFinished,
            events::UpdateStatus,
        ])
}

/// Writes bindings.ts (debug runs and `cargo test`).
fn export_bindings(builder: &Builder<tauri::Wry>) {
    let ts = specta_typescript::Typescript::default()
        .header("// GENERATED by tauri-specta from apps/desktop/src-tauri. Do not edit by hand.\n// @ts-nocheck");
    builder.export(ts, BINDINGS_PATH).expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    bench::mark_start();
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    let context = tauri::generate_context!();
    // Updates need the public signing key in tauri.conf.json, and only make sense
    // in release builds (BLOCKSY_UPDATER_DEV=1 forces them on for testing).
    let has_key = context
        .config()
        .plugins
        .0
        .get("updater")
        .and_then(|u| u.get("pubkey"))
        .and_then(|k| k.as_str())
        .is_some_and(|k| !k.trim().is_empty());
    let updates_enabled = has_key && (!cfg!(debug_assertions) || std::env::var("BLOCKSY_UPDATER_DEV").is_ok());

    let mut app = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .manage(gradle::GradleState::default())
        .manage(updater::UpdaterState::new(updates_enabled));
    if updates_enabled {
        app = app.plugin(tauri_plugin_updater::Builder::new().build());
    }

    app.invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            if cfg!(debug_assertions) {
                app.handle().plugin(tauri_plugin_log::Builder::default().level(log::LevelFilter::Info).build())?;
            }
            updater::start(app.handle().clone());
            Ok(())
        })
        .run(context)
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    /// `cargo test` regenerates bindings.ts, so a stale file shows up as a diff.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder());
    }
}
