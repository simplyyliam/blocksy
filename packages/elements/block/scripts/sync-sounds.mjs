// Regenerates src/sounds.generated.ts: every vanilla block SoundType (STONE, WOOD, ...) with the
// sound event ids it plays when broken, stepped on and placed ("block.wood.break", ...).
// Read with `javap -c` from the Minecraft jars Loom already downloaded on this machine; only
// names are kept (never sound files). A sound type must exist in every pinned version.
// Usage: node packages/elements/block/scripts/sync-sounds.mjs
import { execFileSync } from "node:child_process"
import { writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"

const versions = ["26.1.2", "26.3"]
const maven = join(homedir(), ".gradle/caches/fabric-loom/minecraftMaven/net/minecraft/minecraft-common-deobf")
const javap = (jar, cls) => execFileSync("javap", ["-c", "-cp", jar, cls], { encoding: "utf8", maxBuffer: 64 << 20 })

/** SoundEvents field -> event id, from its static initializer (ldc "id" ... putstatic FIELD). */
function soundEvents(jar) {
  const out = new Map()
  let last = null
  for (const line of javap(jar, "net.minecraft.sounds.SoundEvents").split("\n")) {
    const ldc = /ldc(?:_w)?\s+#\d+\s+\/\/ String (\S+)/.exec(line)
    if (ldc) last = ldc[1]
    const put = /putstatic\s+#\d+\s+\/\/ Field (\w+):/.exec(line)
    if (put && last) {
      out.set(put[1], last)
      last = null
    }
  }
  return out
}

/** SoundType constant -> [break, step, place] SoundEvents fields, in constructor order. */
function soundTypes(jar) {
  const out = new Map()
  let fields = []
  for (const line of javap(jar, "net.minecraft.world.level.block.SoundType").split("\n")) {
    const get = /getstatic\s+#\d+\s+\/\/ Field net\/minecraft\/sounds\/SoundEvents\.(\w+):/.exec(line)
    if (get) fields.push(get[1])
    const put = /putstatic\s+#\d+\s+\/\/ Field (\w+):Lnet\/minecraft\/world\/level\/block\/SoundType;/.exec(line)
    if (put) {
      if (put[1] !== "EMPTY" && fields.length >= 3) out.set(put[1], fields.slice(0, 3))
      fields = []
    }
  }
  return out
}

let result = null
for (const v of versions) {
  const jar = join(maven, v, `minecraft-common-deobf-${v}.jar`)
  const events = soundEvents(jar)
  const types = new Map()
  for (const [name, [brk, step, place]] of soundTypes(jar)) {
    const ids = [brk, step, place].map((f) => events.get(f))
    if (ids.every(Boolean)) types.set(name, { break: ids[0], step: ids[1], place: ids[2] })
  }
  // Keep only sound types every pinned version has, with the same events.
  result = result ? new Map([...result].filter(([k, e]) => types.has(k) && JSON.stringify(types.get(k)) === JSON.stringify(e))) : types
}

const list = [...result].map(([name, events]) => ({ id: name.toLowerCase(), events }))
writeFileSync(
  new URL("../src/sounds.generated.ts", import.meta.url),
  `// GENERATED by scripts/sync-sounds.mjs from Minecraft ${versions.join(" + ")}. Do not edit by hand.\n` +
    `// Every block SoundType (SoundType.<ID>) and the sound events it plays. Names only, no sounds.\n` +
    `export const SOUND_TYPES = ${JSON.stringify(list, null, 1)} as const\n`,
)
console.log(`${list.length} sound types`)
