// Regenerates src/vanilla.generated.ts: every vanilla item id and tag id, read from the
// Minecraft jars Loom already downloaded on this machine (run a Fabric build once first).
// Only ids are kept (facts you need to reference items), never textures, models or code.
// Usage: node packages/game-data/scripts/sync-vanilla-ids.mjs [minecraft version...]
import { execFileSync } from "node:child_process"
import { existsSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"

const versions = process.argv.slice(2).length ? process.argv.slice(2) : ["26.1.2", "26.3"]
const maven = join(homedir(), ".gradle/caches/fabric-loom/minecraftMaven/net/minecraft")
const list = (jar) => execFileSync("jar", ["tf", jar], { encoding: "utf8", maxBuffer: 64 << 20 }).split(/\r?\n/)

const items = new Set()
const itemTags = new Set()
const blockTags = new Set()
for (const v of versions) {
  const client = join(maven, `minecraft-clientonly-deobf/${v}/minecraft-clientonly-deobf-${v}.jar`)
  const common = join(maven, `minecraft-common-deobf/${v}/minecraft-common-deobf-${v}.jar`)
  if (!existsSync(client) || !existsSync(common)) throw new Error(`Minecraft ${v} isn't in the Gradle cache yet`)
  for (const f of list(client)) {
    const m = /^assets\/minecraft\/items\/([a-z0-9_]+)\.json$/.exec(f)
    if (m) items.add(m[1])
  }
  for (const f of list(common)) {
    const item = /^data\/minecraft\/tags\/item\/([a-z0-9_/]+)\.json$/.exec(f)
    if (item) itemTags.add(item[1])
    const block = /^data\/minecraft\/tags\/block\/([a-z0-9_/]+)\.json$/.exec(f)
    if (block) blockTags.add(block[1])
  }
}

const out = (name, set) => `export const ${name}: readonly string[] = ${JSON.stringify([...set].sort())}\n`
writeFileSync(
  new URL("../src/vanilla.generated.ts", import.meta.url),
  `// GENERATED by scripts/sync-vanilla-ids.mjs from Minecraft ${versions.join(" + ")}. Do not edit by hand.\n` +
    `// Ids only (minecraft:<id>), so recipes and tags can reference vanilla things.\n` +
    out("VANILLA_ITEMS", items) + out("VANILLA_ITEM_TAGS", itemTags) + out("VANILLA_BLOCK_TAGS", blockTags),
)
console.log(`${items.size} items, ${itemTags.size} item tags, ${blockTags.size} block tags`)
