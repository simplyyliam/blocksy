// Turns the Gradle wrapper files in ../wrapper/ into src/wrapper.generated.ts,
// so the generator can stay pure (it only returns strings, it never reads disk).
// Run after replacing the wrapper: pnpm --filter @blocksy/target-fabric sync-wrapper
import { readFileSync, writeFileSync } from "node:fs"

const dir = new URL("../wrapper/", import.meta.url)
const read = (name) => readFileSync(new URL(name, dir))

const out = `// GENERATED by scripts/sync-wrapper.mjs from wrapper/. Do not edit by hand.
// Gradle wrapper (Apache-2.0), taken from FabricMC/fabric-example-mod.

export const GRADLEW = ${JSON.stringify(read("gradlew").toString("utf8"))}

export const GRADLEW_BAT = ${JSON.stringify(read("gradlew.bat").toString("utf8"))}

export const GRADLE_WRAPPER_JAR_BASE64 = ${JSON.stringify(read("gradle-wrapper.jar").toString("base64"))}
`
writeFileSync(new URL("../src/wrapper.generated.ts", import.meta.url), out)
console.log("wrote src/wrapper.generated.ts")
