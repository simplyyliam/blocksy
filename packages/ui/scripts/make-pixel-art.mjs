// Draws the Minecraft theme's pixel art: original textures made by code (seeded noise
// and Blocksy's own palette), never Mojang's. Writes them as base64 PNGs into
// src/theme/minecraft-art.generated.ts, which the theme uses as token values.
// Run: node packages/ui/scripts/make-pixel-art.mjs
import { writeFileSync } from "node:fs"
import { deflateSync } from "node:zlib"

const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
  return c >>> 0
})
const crc32 = (buf) => {
  let c = 0xffffffff
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8)
  return (c ^ 0xffffffff) >>> 0
}
const chunk = (type, data) => {
  const body = Buffer.concat([Buffer.from(type), data])
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([len, body, crc])
}
function png(w, h, pixel) {
  const raw = Buffer.alloc((w * 4 + 1) * h)
  for (let y = 0; y < h; y++) {
    raw[y * (w * 4 + 1)] = 0
    for (let x = 0; x < w; x++) raw.set(pixel(x, y), y * (w * 4 + 1) + 1 + x * 4)
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(w, 0)
  ihdr.writeUInt32BE(h, 4)
  ihdr.set([8, 6, 0, 0, 0], 8)
  const sig = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10])
  return Buffer.concat([sig, chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw)), chunk("IEND", Buffer.alloc(0))]).toString("base64")
}
function random(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
const hex = (h) => [parseInt(h.slice(1, 3), 16), parseInt(h.slice(3, 5), 16), parseInt(h.slice(5, 7), 16), 255]

// 1. Deep stone: soft blotches of three close tones, tiles seamlessly (32x32).
function stone() {
  const r = random(11)
  const tones = ["#1d1b20", "#211f25", "#25232a"].map(hex)
  const grid = Array.from({ length: 32 * 32 }, () => (r() < 0.55 ? 1 : r() < 0.5 ? 0 : 2))
  return png(32, 32, (x, y) => tones[grid[y * 32 + x]])
}

// 2. Planks: horizontal boards with darker seams and a few knots (32x32), for side panels.
function planks() {
  const r = random(23)
  const tones = ["#2a2420", "#2e2823", "#332c26", "#1f1a17"].map(hex)
  return png(32, 32, (x, y) => {
    if (y % 8 === 7) return tones[3] // seam between boards
    const board = Math.floor(y / 8)
    if ((x + board * 13) % 32 === 0) return tones[3] // board ends, staggered
    const v = r()
    return tones[v < 0.15 ? 0 : v < 0.85 ? 1 : 2]
  })
}

// 3. Grass edge: a 16x4 strip, green on top dripping into dirt, for decorative borders.
function grass() {
  const r = random(5)
  const green = ["#4e9a3e", "#5cbf4a", "#3f8433"].map(hex)
  const dirt = ["#5a3e2b", "#4a3324"].map(hex)
  const drip = Array.from({ length: 16 }, () => 1 + Math.floor(r() * 3))
  return png(16, 4, (x, y) => (y < drip[x] ? green[Math.floor(r() * 3)] : dirt[Math.floor(r() * 2)]))
}

const out = `// Generated by packages/ui/scripts/make-pixel-art.mjs: original pixel art, drawn by code.
// Do not edit by hand; change the script and run it again.
export const STONE_PNG = "${stone()}"
export const PLANKS_PNG = "${planks()}"
export const GRASS_PNG = "${grass()}"
`
writeFileSync(new URL("../src/theme/minecraft-art.generated.ts", import.meta.url), out)
console.log("wrote src/theme/minecraft-art.generated.ts")
